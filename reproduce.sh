#!/usr/bin/env bash
# Reproduce the results of the report from this repository, on any Linux or macOS machine with Python 3.10+.
#
#   bash reproduce.sh            unit tests + every table, figure and number of the report recomputed from the stored
#                                run files + 3 trained teams (one per question) replayed on their validation matches
#                                (about 5-10 minutes)
#   bash reproduce.sh --full     the same, but the 3 teams replay their full 300-match test (about 10-30 minutes more)
#   bash reproduce.sh --all      the same, and every one of the 65 trained teams replays its validation matches
#                                (about 30-60 minutes on 8 cores)
#
# Nothing is trained and no committed file is changed: everything recomputed goes to reproduce_out/ and is compared
# there with the committed version. The first run creates .venv/ and installs requirements.txt (CPU-only torch).
set -u
cd "$(dirname "$0")"
ROOT=$(pwd)
OUT="$ROOT/reproduce_out"
FULL=0; ALL=0
for a in "$@"; do
  case "$a" in
    --full) FULL=1 ;;
    --all)  ALL=1 ;;
    -h|--help) sed -n '2,13p' "$0"; exit 0 ;;
    *) echo "unknown option $a (use --full, --all or --help)"; exit 2 ;;
  esac
done

# ---------------------------------------------------------------------------------------------------- 0. Python
PY=python3
if [ -x .venv/bin/python ]; then
  PY=.venv/bin/python
elif ! python3 -c "import torch, numpy, yaml, matplotlib, pytest" 2>/dev/null; then
  echo "== 0. setting up .venv (first run only)"
  python3 -m venv .venv || { echo "could not create a virtual environment (on Ubuntu: sudo apt install python3-venv)"; exit 1; }
  PY=.venv/bin/python
  $PY -m pip install -q --upgrade pip
  if [ "$(uname)" = "Linux" ]; then
    $PY -m pip install -q torch --index-url https://download.pytorch.org/whl/cpu || exit 1
  fi
  $PY -m pip install -q -r requirements.txt || exit 1
fi
PY=$(cd "$(dirname "$PY")" && pwd)/$(basename "$PY")
echo "== using $($PY --version) at $PY, torch $($PY -c 'import torch; print(torch.__version__)')"
PROCS=$($PY -c "import os; print(max(1, (os.cpu_count() or 2) - 1))")

rm -rf "$OUT"; mkdir -p "$OUT/docs" "$OUT/paper"
cd football_adapt
export PYTHONPATH=.
FAIL=0
step() { echo; echo "== $1"; }
result() { if [ "$1" -eq 0 ]; then echo "   PASS: $2"; else echo "   FAIL: $2"; FAIL=1; fi; }

# ---------------------------------------------------------------------------------------------------- 1. tests
step "1. unit tests of the game, the opponent, the rewards and the filters (about 2 minutes)"
$PY -m pytest -q -p no:cacheprovider tests > "$OUT/tests.log" 2>&1
r=$?; tail -1 "$OUT/tests.log"; result $r "unit tests (log: reproduce_out/tests.log)"

# ---------------------------------------------------------------------------------------------------- 2. tables and figures
step "2. every table, figure and number of the report, recomputed from the stored run files"
cp ../docs/reportQ1.md ../docs/reportQ2.md ../docs/reportQ3.md "$OUT/docs/"
FINAL_DOCS="$OUT/docs" $PY runs/_tools/final_report.py > "$OUT/final_report.log" 2>&1
result $? "runs/_tools/final_report.py ran (tables of docs/results_final.md and docs/reportQ*.md)"
PAPER_OUT="$OUT/paper" $PY ../paper/make_figs.py > "$OUT/make_figs.log" 2>&1
result $? "paper/make_figs.py ran (figures of the paper in reproduce_out/paper/media/)"
grep -v '^Generated by' ../docs/results_final.md > "$OUT/a.md"; grep -v '^Generated by' "$OUT/docs/results_final.md" > "$OUT/b.md"
cmp -s "$OUT/a.md" "$OUT/b.md"; result $? "docs/results_final.md is identical to the recomputed one (apart from its date line)"
rm -f "$OUT/a.md" "$OUT/b.md"
for q in 1 2 3; do
  cmp -s "../docs/reportQ$q.md" "$OUT/docs/reportQ$q.md"; result $? "the tables of docs/reportQ$q.md are identical to the recomputed ones"
done
cmp -s ../paper/numbers.txt "$OUT/paper/numbers.txt"
result $? "paper/numbers.txt (every number quoted in the paper, with its source file) is identical to the recomputed one"

# ---------------------------------------------------------------------------------------------------- 3. replay
step "3. trained teams replayed: load the stored best checkpoint, play the same matches with the same seeds"
echo "   (W must agree; on a different CPU or torch version a match can occasionally end differently, see README)"
SEL="runs/q1/z1_r25/s0 runs/q2/gru_r25_z0/s0 runs/q3/mixw_r25_z0/s0"
$PY -m scripts.replay_test --quick $SEL --procs "$PROCS" --tolerance 0.05 | tee "$OUT/replay_quick.txt"
result ${PIPESTATUS[0]} "3 teams (Q1, Q2, Q3) replayed on their 50 validation matches"
if [ $FULL -eq 1 ]; then
  $PY -m scripts.replay_test $SEL --procs "$PROCS" --tolerance 0.03 | tee "$OUT/replay_full.txt"
  result ${PIPESTATUS[0]} "3 teams replayed on their full 300-match test"
fi
if [ $ALL -eq 1 ]; then
  RUNS=$(find runs/q1 runs/q2 runs/q3 -name result.json | xargs -n1 dirname | sort)
  $PY -m scripts.replay_test --quick $RUNS --procs "$PROCS" --tolerance 0.05 | tee "$OUT/replay_all.txt"
  result ${PIPESTATUS[0]} "all $(echo "$RUNS" | wc -w) trained teams replayed on their validation matches"
fi

echo
if [ $FAIL -eq 0 ]; then echo "== ALL CHECKS PASSED (outputs in reproduce_out/)"; else echo "== SOME CHECKS FAILED (see above and reproduce_out/)"; fi
exit $FAIL
